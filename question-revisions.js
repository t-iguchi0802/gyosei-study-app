  const revised = JSON.parse(JSON.stringify(original));
  revised.contentRevision = edition;
  revised.questions.forEach(question => { question.contentRevision = baseline; });
  for (const revision of revisions) {
    const question = revised.questions.find(item => item.id === revision.id);
    if (!question || question.type !== "single" || revision.choices.length !== 5 || revision.reasons.length !== 5) {
      throw new Error(`Invalid question revision: ${revision.id}`);
    }
    question.prompt = revision.prompt;
    question.contentRevision = edition;
    question.choices = revision.choices.map((label, index) => ({ value: index + 1, label, trap: traps[revision.id][index] || null }));
    Object.keys(question.sections).filter(name => /^肢\d+\s/.test(name)).forEach(name => delete question.sections[name]);
    revision.reasons.forEach((reason, index) => {
      const value = index + 1;
      question.sections[`肢${value} ${value === question.answer ? "○" : "×"}`] = reason;
    });
    if (revision.core) question.core = question.sections["この問題の核心"] = revision.core;
    question.sections["出題者の罠"] = revision.trap;
    question.sections["解答テクニック"] = revision.technique;
    if (revision.grounds) question.sections["根拠条文"] = revision.grounds;
    // Keep original sources as well as version-pinned sources of the revision.
    question.sections["一次資料"] = [question.sections["一次資料"], revision.refs].filter(Boolean).join("\n");
  }
